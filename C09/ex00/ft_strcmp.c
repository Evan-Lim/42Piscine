int	ft_strcmp(char *s1, char *s2)
{
	int				i;
	unsigned char	uc[2];

	i = 0;
	while (s1[i] && s1[i] == s2[i])
		i++;
	uc[0] = (unsigned char)s1[i];
	uc[1] = (unsigned char)s2[i];
	return (uc[0] - uc[1]);
}
